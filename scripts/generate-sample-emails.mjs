/**
 * Runs every author in the dataset through the live workflow and saves the
 * emails, so prompt quality can be reviewed across all the edge cases (paid
 * up, overdue, never paid, below ₹1,000, books in production).
 *
 *   npm run emails                       -> as of today
 *   npm run emails -- --as-of 2026-01-01 -> as of the dataset snapshot date
 *
 * Calls are spaced 7 s apart to stay inside Gemini's free-tier rate limit.
 */
import { mkdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { bubblePayload, dataset } from "./lib/payload.mjs";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const asOfFlag = process.argv.indexOf("--as-of");
const asOfIso = asOfFlag > -1 ? process.argv[asOfFlag + 1] : null;
const label = asOfIso ? `as-of-${asOfIso}` : `as-of-${new Date().toISOString().slice(0, 10)}`;
const outDir = path.join(ROOT, "docs/sample-emails", label);
mkdirSync(outDir, { recursive: true });

const rows = [];
for (const [i, author] of dataset.authors.entries()) {
  if (i > 0) await new Promise((r) => setTimeout(r, 7000));
  const body = bubblePayload(author.author_id, { asOfIso: asOfIso ?? undefined, notificationId: `sample-${label}-${author.author_id}-${Date.now()}` });
  const started = Date.now();
  const res = await fetch(process.env.N8N_WEBHOOK_URL, {
    method: "POST",
    headers: { "Content-Type": "application/json", "X-BookLeaf-Key": process.env.N8N_WEBHOOK_KEY },
    body: JSON.stringify(body),
  });
  const j = await res.json();
  const slug = `${author.author_id}-${author.name.toLowerCase().replace(/\s+/g, "-")}`;
  if (j.email_html) writeFileSync(path.join(outDir, `${slug}.html`), j.email_html);
  if (j.email_text) writeFileSync(path.join(outDir, `${slug}.txt`), `Subject: ${j.email_subject}\n\n${j.email_text}\n`);
  rows.push({ author: author.name, slug, status: j.status, subject: j.email_subject, model: j.ai_model, attempts: j.ai_attempts, ms: Date.now() - started, error: j.error_message });
  console.log(`${author.author_id} ${author.name.padEnd(16)} ${j.status.padEnd(9)} ${j.ai_model || ""} x${j.ai_attempts} ${Date.now() - started}ms  ${j.email_subject || j.error_message}`);
}

const md = [
  `# Sample royalty summaries (${asOfIso ? `as of ${asOfIso}` : "as of the day they were generated"})`,
  "",
  "Generated by `npm run emails` through the real workflow (Gemini free tier). Open the `.html` files in a browser; `.txt` is the plain-text part.",
  "",
  "| Author | Status | Subject | Model (attempts) | Time |",
  "|---|---|---|---|---|",
  ...rows.map((r) => `| [${r.author}](${r.slug}.html) | ${r.status} | ${r.subject || r.error} | ${r.model} (${r.attempts}) | ${(r.ms / 1000).toFixed(1)} s |`),
  "",
].join("\n");
writeFileSync(path.join(outDir, "README.md"), md);
console.log(`\nSaved to ${path.relative(ROOT, outDir)}`);
